# backend/app/models/curriculum.py
"""Curriculum reference data: boards, subjects, specifications and their content.

Everything here is loaded from YAML files under ``curriculum/`` by the import
command. It's never generated by a model (ADR-012).
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum

from sqlalchemy import (
    ARRAY,
    Boolean,
    CheckConstraint,
    DateTime,
    Enum,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    Uuid,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, TimestampMixin


class Tier(StrEnum):
    """Exam tier. Untiered subjects use ``None`` instead."""

    FOUNDATION = "foundation"
    HIGHER = "higher"


TIER_ENUM = Enum(Tier, name="tier", values_callable=lambda e: [m.value for m in e])


class ExamBoard(Base):
    """An awarding body, e.g. AQA."""

    __tablename__ = "exam_boards"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    code: Mapped[str] = mapped_column(String(32), unique=True, nullable=False)
    name: Mapped[str] = mapped_column(String(80), nullable=False)
    position: Mapped[int] = mapped_column(Integer, nullable=False, server_default=text("0"))


class Subject(Base):
    """A GCSE subject the student can choose, independent of board."""

    __tablename__ = "subjects"

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    slug: Mapped[str] = mapped_column(String(64), unique=True, nullable=False)
    name: Mapped[str] = mapped_column(String(80), nullable=False)
    has_tiers: Mapped[bool] = mapped_column(Boolean, nullable=False)
    # Categories of set text the student chooses (e.g. "Shakespeare play");
    # empty for subjects without set texts.
    set_text_categories: Mapped[list[str]] = mapped_column(
        ARRAY(String(80)), nullable=False, server_default=text("'{}'")
    )
    # The board most schools use for this subject. Only a starting suggestion
    # on the setup screen; the student or admin can change it.
    most_common_board_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("exam_boards.id", ondelete="SET NULL")
    )
    position: Mapped[int] = mapped_column(Integer, nullable=False, server_default=text("0"))


class Specification(TimestampMixin, Base):
    """One exact version of a board's specification for a subject."""

    __tablename__ = "specifications"
    __table_args__ = (
        UniqueConstraint("board_id", "code", "version"),
        # At most one current version per board + spec code.
        Index(
            "uq_specifications_current",
            "board_id",
            "code",
            unique=True,
            postgresql_where=text("is_current"),
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    subject_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("subjects.id", ondelete="RESTRICT"), nullable=False, index=True
    )
    board_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("exam_boards.id", ondelete="RESTRICT"), nullable=False
    )
    code: Mapped[str] = mapped_column(String(32), nullable=False)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    version: Mapped[str] = mapped_column(String(80), nullable=False)
    source_url: Mapped[str | None] = mapped_column(String(500))
    tiered: Mapped[bool] = mapped_column(Boolean, nullable=False)
    is_current: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("true"))
    source_file: Mapped[str] = mapped_column(String(300), nullable=False)


class Topic(Base):
    """A top-level spec section, e.g. "1. Number"."""

    __tablename__ = "topics"
    __table_args__ = (UniqueConstraint("specification_id", "ref"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    specification_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("specifications.id", ondelete="CASCADE"), nullable=False
    )
    ref: Mapped[str] = mapped_column(String(32), nullable=False)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    position: Mapped[int] = mapped_column(Integer, nullable=False)
    retired_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class Subtopic(Base):
    """A heading inside a topic, e.g. "Structure and calculation"."""

    __tablename__ = "subtopics"
    __table_args__ = (UniqueConstraint("topic_id", "title"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    topic_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("topics.id", ondelete="CASCADE"), nullable=False, index=True
    )
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    position: Mapped[int] = mapped_column(Integer, nullable=False)
    retired_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class LearningObjective(Base):
    """One spec statement, with its exact wording per tier.

    - ``foundation_text``: wording every student is taught. For tiered specs,
      the Foundation-tier wording; ``None`` if the statement is Higher-only.
      Untiered specs keep all wording here.
    - ``higher_text``: the Higher-tier wording when it differs from (usually
      extends) the Foundation wording; ``None`` if identical or untiered.

    Use :meth:`text_for` rather than reading the columns directly.
    """

    def text_for(self, tier: Tier | None) -> str | None:
        """Return the wording a student on ``tier`` is assessed on.

        Args:
            tier: The student's tier, or ``None`` for an untiered subject.

        Returns:
            The wording, or ``None`` if this objective isn't on that tier.
        """
        if tier is Tier.HIGHER:
            return self.higher_text or self.foundation_text
        return self.foundation_text

    __tablename__ = "learning_objectives"
    __table_args__ = (
        UniqueConstraint("specification_id", "ref"),
        CheckConstraint(
            "foundation_text IS NOT NULL OR higher_text IS NOT NULL", name="has_wording"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    specification_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("specifications.id", ondelete="CASCADE"), nullable=False
    )
    subtopic_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("subtopics.id", ondelete="CASCADE"), nullable=False, index=True
    )
    ref: Mapped[str] = mapped_column(String(32), nullable=False)
    foundation_text: Mapped[str | None] = mapped_column(Text)
    higher_text: Mapped[str | None] = mapped_column(Text)
    keywords: Mapped[list[str]] = mapped_column(
        ARRAY(String(80)), nullable=False, server_default=text("'{}'")
    )
    out_of_scope: Mapped[str | None] = mapped_column(Text)
    position: Mapped[int] = mapped_column(Integer, nullable=False)
    retired_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class SetTextOption(Base):
    """A set text the board allows, e.g. "Macbeth" in "Shakespeare play"."""

    __tablename__ = "set_text_options"
    __table_args__ = (UniqueConstraint("specification_id", "category", "title"),)

    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    specification_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("specifications.id", ondelete="CASCADE"), nullable=False, index=True
    )
    category: Mapped[str] = mapped_column(String(80), nullable=False)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    author: Mapped[str | None] = mapped_column(String(120))
    position: Mapped[int] = mapped_column(Integer, nullable=False)
    retired_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


